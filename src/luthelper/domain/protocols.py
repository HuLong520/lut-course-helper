from __future__ import annotations

from pathlib import Path
from typing import Protocol

from .models import Batch, Course, RobOutcome, SelectedCourse, Student


class LutClientProtocol(Protocol):
    def load_login_config(self) -> None: ...

    def get_captcha(self) -> tuple[bytes, str, int]: ...

    def login(self, username: str, password: str, captcha: str) -> str: ...

    def get_student(self) -> Student: ...

    def get_batches(self) -> list[Batch]: ...

    def confirm_batch(self, batch_id: str) -> None: ...

    def list_courses(
        self,
        class_type: str,
        campus: str,
        page_size: int = 500,
        cancel: object | None = None,
    ) -> list[Course]: ...

    def list_selected(self) -> list[SelectedCourse]: ...

    def add_course(self, clazz_type: str, clazz_id: str, secret_val: str) -> RobOutcome: ...

    def close(self) -> None: ...


class CredentialStoreProtocol(Protocol):
    def load(self) -> list[dict[str, str]]: ...

    def upsert(self, username: str, password: str) -> None: ...

    def delete(self, username: str) -> None: ...

    def record_login_time(self, username: str) -> None: ...

    @property
    def path(self) -> Path: ...
